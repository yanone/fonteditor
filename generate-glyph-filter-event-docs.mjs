#!/usr/bin/env node

/**
 * Glyph Filter Event Documentation Generator
 *
 * Transpiles the typed registry in memory and renders its public contract.
 *
 * Usage:
 *   node generate-glyph-filter-event-docs.mjs
 */

import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join, relative } from 'path';
import ts from 'typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const REGISTRY_PATH = join(__dirname, 'webapp', 'js', 'glyph-filter-events.ts');
const OUTPUT_PATH = join(
    __dirname,
    'developer-docs',
    'GLYPH_FILTER_EVENTS.md'
);

/** Loads the TypeScript-only registry without requiring a separate build step. */
async function loadRegistry() {
    const source = readFileSync(REGISTRY_PATH, 'utf-8');
    const output = ts.transpileModule(source, {
        compilerOptions: {
            module: ts.ModuleKind.ESNext,
            target: ts.ScriptTarget.ES2021
        },
        fileName: REGISTRY_PATH
    }).outputText;
    const encoded = Buffer.from(output).toString('base64');
    return import(`data:text/javascript;base64,${encoded}`);
}

function renderMarkdown(eventTypes, registry) {
    const lines = [
        '# Glyph Filter Event Reference',
        '',
        '> Generated by `node generate-glyph-filter-event-docs.mjs`. Do not edit this file by hand.',
        '',
        'This document defines the central event contract that glyph filters may use to decide when to refresh.',
        '',
        '## Incremental Results',
        '',
        '`filter_glyphs(font)` produces the complete reconciliation result. Optional `apply_changes(change_batch, current_results, font)` appears after it and returns `None` for complete reconciliation or an idempotent delta:',
        '',
        '```python',
        "{'add': ['adieresis'], 'remove': ['aacute']}",
        '```',
        '',
        '`add` also accepts the normal filter-result dictionaries when group membership must be supplied or replaced:',
        '',
        '```python',
        "{'add': [{'glyph_name': 'adieresis', 'groups': ['latin_ext_a']}], 'remove': ['adieresis']}",
        '```',
        '',
        'The host removes first, then adds. Removing an absent glyph and adding an already-present glyph are no-ops.',
        '',
        '## Events',
        ''
    ];

    for (const type of eventTypes) {
        const event = registry[type];
        lines.push(`## \`${type}\``);
        lines.push('');
        lines.push(`- Name: ${event.name}`);
        lines.push(`- Description: ${event.description}`);
        lines.push('');
        lines.push('### Metadata');
        lines.push('');
        lines.push('| Field | Type | Required | Description |');
        lines.push('| --- | --- | --- | --- |');
        for (const field of event.metadataFields) {
            lines.push(
                `| \`${field.name}\` | \`${field.type}\` | ${field.required ? 'Yes' : 'No'} | ${field.description} |`
            );
        }
        lines.push('');
    }

    return `${lines.join('\n')}\n`;
}

async function main() {
    const { GLYPH_FILTER_EVENT_REGISTRY, GLYPH_FILTER_EVENT_TYPES } =
        await loadRegistry();
    writeFileSync(
        OUTPUT_PATH,
        renderMarkdown(GLYPH_FILTER_EVENT_TYPES, GLYPH_FILTER_EVENT_REGISTRY),
        'utf-8'
    );
    console.log(
        `Generated ${GLYPH_FILTER_EVENT_TYPES.length} glyph filter event reference entries at ${relative(__dirname, OUTPUT_PATH)}`
    );
}

main();
